export function translate(message, language = 'en', variables = {}) {
  const source = String(message ?? '')
  const template = language === 'ar' ? (arabicMessages[source] || source) : source
  return template.replace(/\{(\w+)\}/g, (match, key) =>
    Object.prototype.hasOwnProperty.call(variables, key) ? String(variables[key]) : match,
  )
}

export function useTranslation() {
  const language = usePreferencesStore((state) => state.language || 'en')
  const toggleLanguage = usePreferencesStore((state) => state.toggleLanguage)
  const t = useCallback((message, variables) => translate(message, language, variables), [language])
  return { language, isArabic: language === 'ar', t, toggleLanguage }
}
